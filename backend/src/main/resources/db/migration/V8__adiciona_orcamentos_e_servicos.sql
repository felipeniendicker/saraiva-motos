CREATE TABLE orcamento (
    id BIGINT NOT NULL AUTO_INCREMENT,
    numero VARCHAR(30) NOT NULL,
    cliente_id BIGINT NULL,
    cliente_nome VARCHAR(180) NULL,
    cliente_tipo VARCHAR(30) NULL,
    tipo_preco_utilizado VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_emissao DATETIME(6) NOT NULL,
    data_atualizacao DATETIME(6) NOT NULL,
    validade DATE NOT NULL,
    subtotal DECIMAL(15, 2) NOT NULL,
    desconto DECIMAL(15, 2) NOT NULL,
    desconto_percentual DECIMAL(7, 4) NOT NULL,
    total DECIMAL(15, 2) NOT NULL,
    observacoes TEXT NULL,
    operador_id BIGINT NOT NULL,
    operador_email VARCHAR(254) NOT NULL,
    venda_id BIGINT NULL,
    data_cancelamento DATETIME(6) NULL,
    motivo_cancelamento VARCHAR(1000) NULL,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_orcamento PRIMARY KEY (id),
    CONSTRAINT uk_orcamento_numero UNIQUE (numero),
    CONSTRAINT uk_orcamento_venda UNIQUE (venda_id),
    CONSTRAINT fk_orcamento_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT fk_orcamento_operador FOREIGN KEY (operador_id) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_orcamento_venda FOREIGN KEY (venda_id) REFERENCES venda (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_orcamento_status CHECK (status IN ('RASCUNHO', 'EMITIDO', 'CONVERTIDO', 'CANCELADO')),
    CONSTRAINT chk_orcamento_valores CHECK (subtotal >= 0 AND desconto >= 0 AND total >= 0 AND desconto_percentual BETWEEN 0 AND 100),
    INDEX idx_orcamento_data_emissao (data_emissao),
    INDEX idx_orcamento_cliente (cliente_id),
    INDEX idx_orcamento_status (status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE item_orcamento (
    id BIGINT NOT NULL AUTO_INCREMENT,
    orcamento_id BIGINT NOT NULL,
    tipo_item VARCHAR(20) NOT NULL,
    produto_id BIGINT NULL,
    codigo_item VARCHAR(100) NOT NULL,
    descricao_item VARCHAR(180) NOT NULL,
    quantidade INT NOT NULL,
    preco_original DECIMAL(15, 2) NOT NULL,
    preco_unitario DECIMAL(15, 2) NOT NULL,
    preco_alterado_manualmente BOOLEAN NOT NULL DEFAULT FALSE,
    subtotal DECIMAL(15, 2) NOT NULL,
    CONSTRAINT pk_item_orcamento PRIMARY KEY (id),
    CONSTRAINT fk_item_orcamento_orcamento FOREIGN KEY (orcamento_id) REFERENCES orcamento (id) ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_item_orcamento_produto FOREIGN KEY (produto_id) REFERENCES produto (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_item_orcamento_tipo CHECK (tipo_item IN ('PRODUTO', 'SERVICO')),
    CONSTRAINT chk_item_orcamento_quantidade CHECK (quantidade > 0),
    CONSTRAINT chk_item_orcamento_valores CHECK (preco_original >= 0 AND preco_unitario >= 0 AND subtotal >= 0),
    INDEX idx_item_orcamento_orcamento (orcamento_id),
    INDEX idx_item_orcamento_produto (produto_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
